#!/usr/bin/env python3
"""Export Tidy's live public API and optionally regenerate the agent cheat sheet."""

import argparse
import json
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
SHEET = ROOT / 'skills/deixis/references/api.md'


def export_api(typst='typst'):
    expression = ('{ import "docs/reference/catalog.typ" as api; '
                  '(groups: api.groups, functions: api.functions, exports: api.exports) }')
    result = subprocess.run([typst, 'eval', '--root', str(ROOT), '--format', 'json', expression],
                            cwd=ROOT, text=True, capture_output=True, timeout=120)
    if result.returncode or result.stderr:
        raise RuntimeError(result.stderr or result.stdout)
    data = json.loads(result.stdout)
    data['version'] = tomllib.loads((ROOT / 'typst.toml').read_text())['package']['version']
    return data


def signature(function):
    if 'args' not in function:
        return function['name']
    arguments = []
    for name, info in function.get('args', {}).items():
        arguments.append(name + (': ' + info['default'] if 'default' in info else ''))
    return function['name'] + '(' + ', '.join(arguments) + ')'


def cheat_sheet(data):
    functions = {f['name']: f for f in data['functions']}
    lines = ['# Deixis API Cheat Sheet', '',
             '<!-- Generated by scripts/export-api.py --skill. Do not edit by hand. -->', '',
             f'Deixis {data["version"]}; Typst 0.15.0+. Names and selected defaults come',
             'from the public source through Tidy and the manual catalog. `auto` can',
             'resolve through scoped/factory settings. Grouped defaults belong to the',
             'first function; the website API pages show each full signature.', '',
             'Setup: **setup** requires document setup; **free** needs none;',
             '**conditional** depends on document lookup; **installs** provides setup.', '']
    for group in data['groups']:
        lines += ['## ' + group['title'], '', group['intro'], '']
        for entry in group['entries']:
            lines += ['### ' + ' / '.join('`' + n + '`' for n in entry['names']), '',
                      entry['summary'], '', 'Setup: **' + entry['setup'] + '**.']
            args = functions[entry['names'][0]].get('args', {})
            selected = [name + (' = ' + args[name]['default'] if 'default' in args[name] else ' (required)')
                        for name in entry['args']]
            if selected:
                lines += ['', 'Selected parameters: ' + '; '.join('`' + a + '`' for a in selected) + '.']
            if entry.get('note'):
                lines += ['', entry['note']]
            lines += ['']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--typst', default='typst')
    parser.add_argument('--output', type=Path, default=ROOT / 'target/api/catalog.json')
    parser.add_argument('--skill', action='store_true', help='Write the generated skill cheat sheet.')
    parser.add_argument('--check-skill', action='store_true', help='Fail if the generated cheat sheet is stale.')
    args = parser.parse_args()
    data = export_api(args.typst)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(data, indent=2) + '\n')
    if args.check_skill and (not SHEET.is_file() or SHEET.read_text() != cheat_sheet(data)):
        raise SystemExit('Skill API cheat sheet is stale: run scripts/export-api.py --skill.')
    if args.skill:
        SHEET.parent.mkdir(parents=True, exist_ok=True)
        SHEET.write_text(cheat_sheet(data))
    print(f'Exported {len(data["exports"])} public names in {sum(len(g["entries"]) for g in data["groups"])} catalog entries.')


if __name__ == '__main__':
    main()
